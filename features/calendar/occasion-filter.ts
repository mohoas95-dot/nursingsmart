/**
 * features/calendar/occasion-filter.ts
 * ---------------------------------------------------------------------------
 * فیلتر «مناسبت‌های مهم» برای فهرست زیر تقویم.
 *
 * چرا لازم بود؟ منبع رسمی تقویم روزانه ده‌ها مناسبت ریز و تبلیغاتی هم برمی‌گرداند
 * («روز عسل»، «روز شیر مادر»، «روز جهانی …» و مانند آن). نوشتن همهٔ آن‌ها زیر
 * تقویم، فهرست را شلوغ و ناخوانا می‌کرد. این ماژول فقط مناسبت‌های تعطیل و
 * مناسبت‌های ملی/مذهبی درجه‌یک را نگه می‌دارد.
 *
 * قاعده‌ها عمداً بر پایهٔ «کلیدواژه» است نه فهرست تاریخ‌های ثابت، چون تاریخ‌ها
 * از منبع رسمی می‌آیند و هر سال جابه‌جا می‌شوند؛ هیچ مناسبتی در این فایل
 * hardcode نشده است.
 */

/** رویدادهای مذهبی و ملی درجه‌یک — همیشه نمایش داده می‌شوند. */
const MAJOR_PATTERNS: RegExp[] = [
  // مناسبت‌های مذهبی
  /ولادت/, /میلاد/, /شهادت/, /رحلت/, /ارتحال/, /وفات/,
  /عید\s?(فطر|قربان|غدیر|سعید|نوروز|مبعث)?/, /مبعث/, /غدیر/,
  /تاسوعا/, /عاشورا/, /اربعین/, /شب\s?قدر/, /نیمه\s?شعبان/,
  /آغاز\s?(ماه\s?)?(رمضان|محرم)/, /روز\s?عرفه/, /هجرت\s?پیامبر/,
  // مناسبت‌های ملی و انقلابی
  /نوروز/, /سیزده\s?به\s?در/, /جشن\s?نوروز/,
  /انقلاب\s?اسلامی/, /پیروزی\s?انقلاب/, /دهه\s?فجر/,
  /جمهوری\s?اسلامی/, /ملی\s?شدن\s?صنعت\s?نفت/,
  /قیام\s?\d{1,2}\s?خرداد/, /آزادسازی\s?خرمشهر/, /فتح\s?خرمشهر/,
  /روز\s?ارتش/, /هفته\s?دفاع\s?مقدس/, /روز\s?جمهوری/,
  // مناسبت‌های صنفی مرتبط با حوزهٔ سلامت و پرستاری
  /روز\s?پرستار/, /روز\s?پزشک/, /هفته\s?سلامت/,
];

/** مناسبت‌های تبلیغاتی/ریز که حتی اگر واژهٔ «روز» داشته باشند حذف می‌شوند. */
const TRIVIAL_PATTERN = /روز\s?(جهانی|ملی|بین‌?المللی)?\s?(عسل|شیر\s?مادر|غذا|قهوه|شکلات|کتاب\s?کودک|اسناد|بیمه|صنعت|آمار|حسابدار|روابط\s?عمومی|تعاون|ترویج|فناوری|مهندسی|جوان|خانواده)/;

/**
 * آیا این مناسبت آن‌قدر مهم هست که زیر تقویم نوشته شود؟
 * @param title عنوان مناسبت از منبع رسمی
 * @param isHoliday آیا آن روز رسماً تعطیل است؟ (تعطیل‌ها همیشه نمایش داده می‌شوند)
 */
export function isImportantOccasion(title: string, isHoliday = false): boolean {
  const text = title.trim();
  if (!text) return false;
  // هر مناسبتی که خودش تعطیلی رسمی آورده، بی‌قید و شرط مهم است.
  if (isHoliday) return true;
  if (TRIVIAL_PATTERN.test(text)) return false;
  return MAJOR_PATTERNS.some(pattern => pattern.test(text));
}

/** فهرست مناسبت‌های یک روز را به مهم‌ترین‌ها خلاصه می‌کند. */
export function filterImportantOccasions(titles: readonly string[], isHoliday = false): string[] {
  const unique = [...new Set(titles.map(item => item.trim()).filter(Boolean))];
  const important = unique.filter(title => isImportantOccasion(title, isHoliday));
  // اگر روز تعطیل است ولی هیچ عنوانی رد نشد، دست‌کم یک عنوان نگه داشته می‌شود
  // تا کاربر بداند علت تعطیلی چه بوده است.
  if (important.length === 0 && isHoliday && unique.length > 0) return [unique[0]];
  return important;
}
